# ==================== 十一、资源路径 ====================
# Agent 的 CWD 由通用 UI 决定（= interface.json 所在目录），不能依赖它。
# 所以图片路径以本文件为基准往上找，环境变量可覆盖。
def image_root():
    """返回 image/ 目录的绝对路径。"""
    import os
    from pathlib import Path

    env = os.environ.get("MAACR_IMAGE_DIR")
    if env:
        return Path(env)
    # agent/cr_config.py -> agent -> <repo>/assets/resource/image
    return Path(__file__).resolve().parent.parent / "assets" / "resource" / "image"
